"use strict";
const fs=require("node:fs"),vm=require("node:vm"),assert=require("node:assert/strict"),path=require("node:path");
const src=fs.readFileSync(path.join(__dirname,"discovery.js"),"utf8");
const D=JSON.parse(fs.readFileSync(path.join(__dirname,"discovery-data.json"),"utf8"));
const records=D.items.map(([id,title,artist,date,genre,tag,url,note])=>({id,title,artist,date,genre,tag,url,note}));
const byId=id=>records.find(r=>r.id===id),labelsData=D.labelCatalogue,connections=D.connections;
assert.equal(new Set(records.map(r=>r.id)).size,records.length);
for(const label of labelsData)for(const id of label[2])assert.ok(byId(id), "Unknown record: "+id);
const start=src.indexOf("function profileMatches("),end=src.indexOf("function recommendations(",start);
assert.ok(start>=0&&end>start);
const recommend=vm.runInNewContext(src.slice(start,end)+"\nrecommend",{records,D,labelsData,connections});
const direct=recommend([byId("voodoo")],new Set(),6);
assert.ok(direct.some(x=>x.r.id==="voodoo-pendulum"&&x.reasons.some(y=>y.startsWith("Remix connection"))));
assert.ok(direct.some(x=>x.r.id==="veryape"&&x.reasons.some(y=>y.startsWith("Sample connection"))));
assert.ok(direct.every(x=>x.r.id!=="voodoo"));
const reverse=recommend([byId("veryape")],new Set(),6);
assert.equal(reverse[0].r.id,"voodoo");
const excluded=recommend([byId("voodoo")],new Set(["voodoo-pendulum","veryape"]),6);
assert.ok(excluded.every(x=>!["voodoo-pendulum","veryape"].includes(x.r.id)));
assert.ok(direct.every((x,i)=>i===0||direct[i-1].score>=x.score));
assert.equal(recommend([],new Set()).length,0);
console.log("Discovery recommendation tests passed: direct and reverse relationships, ranking, seed and saved-record exclusions, label references.");
